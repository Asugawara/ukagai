/** Current display language: <html data-lang>, falling back to en. */
export const currentLang = () => (document.documentElement.dataset.lang === "ja" ? "ja" : "en");

/** Look up a message and fill {vars}. Unknown keys return the key itself. */
export function t(key, vars = {}) {
  const s = MESSAGES[currentLang()][key] ?? MESSAGES.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Replace the static text in index.html: [data-i18n] sets textContent, [data-i18n-aria-label] sets aria-label. */
export function applyStatic(root = document) {
  for (const e of root.querySelectorAll("[data-i18n]")) e.textContent = t(e.dataset.i18n);
  for (const e of root.querySelectorAll("[data-i18n-aria-label]")) e.setAttribute("aria-label", t(e.dataset.i18nAriaLabel));
  document.documentElement.lang = currentLang();
}
